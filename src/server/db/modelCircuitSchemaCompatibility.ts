export async function ensureModelCircuitSchemaCompatibility(inspector: ModelCircuitSchemaInspector): Promise<void> {
  const hasRouteChannels = await inspector.tableExists('route_channels');
  if (!hasRouteChannels) return;

  await executeCompatibilitySql(inspector, CREATE_TABLE_SQL[inspector.dialect]);
  for (const statement of CREATE_INDEX_SQL[inspector.dialect]) {
    await executeCompatibilitySql(inspector, statement);
  }
}
