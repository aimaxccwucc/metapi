export type ModelCircuitSchemaDialect = 'sqlite' | 'mysql' | 'postgres';

export interface ModelCircuitSchemaInspector {
  dialect: ModelCircuitSchemaDialect;
  tableExists(table: string): Promise<boolean>;
  execute(sqlText: string): Promise<void>;
}

function normalizeSchemaErrorMessage(error: unknown): string {
  if (typeof error === 'object' && error && 'message' in error) {
    return String((error as { message?: unknown }).message || '');
  }
  return String(error || '');
}

function isExistingSchemaError(error: unknown): boolean {
  const lowered = normalizeSchemaErrorMessage(error).toLowerCase();
  return lowered.includes('already exists')
    || lowered.includes('duplicate key name')
    || lowered.includes('relation') && lowered.includes('already exists');
}

async function executeCompatibilitySql(inspector: ModelCircuitSchemaInspector, sqlText: string): Promise<void> {
  try {
    await inspector.execute(sqlText);
  } catch (error) {
    if (!isExistingSchemaError(error)) {
      throw error;
    }
  }
}

