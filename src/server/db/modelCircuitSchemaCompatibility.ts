  postgres: `CREATE TABLE IF NOT EXISTS "route_model_circuits" ("id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "channel_id" INTEGER NOT NULL, "model_name" TEXT NOT NULL, "state" TEXT NOT NULL DEFAULT 'closed', "fail_count" INTEGER NOT NULL DEFAULT 0, "opened_at" TIMESTAMP, "open_until" TIMESTAMP, "last_error_at" TIMESTAMP, "last_success_at" TIMESTAMP, "probe_in_flight" BOOLEAN NOT NULL DEFAULT false, "updated_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY ("channel_id") REFERENCES "route_channels"("id") ON DELETE CASCADE)`,
